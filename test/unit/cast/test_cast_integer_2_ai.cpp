////////////////////////////////////////////////////////////////////////////////
TEST_F(cast_integer_2_ai, decimal)
{
    std::vector<std::string> datas = dataset();
    std::vector<int64_t> expects = dataset_expect();
    ASSERT_EQ(datas.size(), expects.size());
    for (int i = 0; i < static_cast<int>(datas.size()); i++)
    {
        eco::string_to_integer<int64_t> a(datas[i].c_str(), 10);
        EXPECT_EQ(a.value, expects[i]);
        if (a.value != expects[i])
        {
            printf("[i=%d] %s expect=%ld cast=%ld\n", 
                i, datas[i].c_str(), expects[i], a.value);
        }
    }
    for (int i = 0; i < static_cast<int>(datas.size()); i++)
    {
        int64_t value = atoll(datas[i].c_str());
        EXPECT_EQ(value, expects[i]);
        if (value != expects[i])
        {
            printf("[i=%d] %s expect=%ld atoll=%ld\n", 
                i, datas[i].c_str(), expects[i], value);
        }
    }
}


////////////////////////////////////////////////////////////////////////////////
TEST_F(cast_integer_2_ai, decimal_perf)
{
    int64_t c1 = 0;
    int64_t c2 = 0;
    const int TIMES = 100000;
    int64_t atoi = perf_atoi(c1, TIMES, dataset());
    int64_t cast = perf_cast(c2, TIMES, dataset());
    EXPECT_EQ(c1, c2);
    EXPECT_EQ(atoi, cast);
}