    {
        count = 0;
        eco::test::timer timer;
        for (int i = 0; i < times; i++)
        {
            for (size_t j = 0; j < datas.size(); j++)
            {
                count += atoll(datas[j].c_str());
            }
        }
        return timer.timeup();
    }
