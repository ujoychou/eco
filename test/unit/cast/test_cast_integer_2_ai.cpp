    inline int64_t perf_cast(
        int64_t& count, int times, const std::vector<std::string>& datas)
    {
        count = 0;
        eco::test::timer timer;
        for (int i = 0; i < times; i++)
        {
            for (size_t j = 0; j < datas.size(); j++)
            {
                eco::string_to_integer<int64_t> a(datas[j].c_str(), 10);
                count += a.value;
            }
        }
        return timer.timeup();
    }

