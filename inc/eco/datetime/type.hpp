#include <eco/prec.hpp>
#include <ctime>


eco_namespace(eco);
////////////////////////////////////////////////////////////////////////////////
class datetime
{
public:
	enum
	{
		// iso: "20160510230505".
		iso			= 0x0001,
		// iso_m: "20160510230505100200".
		iso_m		= 0x0002,
		// iso: "20160510 23:05:05".
		iso_t		= 0x0003,
		// iso: "20160510 23:05:05.688675".
		iso_tm		= 0x0004,
		// std: "2016-05-10 23:05:05".
		std			= 0x0005,
		// std: "2016-05-10 23:05:05.688675".
		std_m		= 0x0006,
	};
	typedef int format;

	inline static datetime now()
	{
		return datetime();
	}

	inline const char* stamp(format fmt) const
	{
		return "20250815 10:00:00.234567";
	}


};


////////////////////////////////////////////////////////////////////////////////
eco_namespace_end(eco);
